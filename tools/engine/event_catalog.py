#!/usr/bin/env python3
"""Write or verify the engine's GB Studio event catalog (engine/modretro-chromatic/dist/gb-studio-events.json).

The catalog is what `chromatic_event_describe` answers from and what `rom_build`'s authoring warnings read: every
GB Studio event with its args, defaults, conditions, branches, deprecation and an example, generated by
event_catalog.mjs from the event definitions of the GB Studio the toolchain compiles with, and what those do not say
(replacements and their conversions, examples that need other events) from event_guidance.mjs. Write it again when
that GB Studio or the guidance changes (it is part of the engine: add the `engine/CHANGES.md` line and write the
manifest).

    python tools/engine/event_catalog.py write  [--gb-studio <folder>]
    python tools/engine/event_catalog.py verify [--gb-studio <folder>]

The folder defaults to the toolchain's own copy, `<setup root>/toolchain/.local/vendor/gb-studio`.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from engine_dev import paths  # noqa: E402 - tools/engine goes on sys.path first

GENERATOR = Path(__file__).resolve().with_name("event_catalog.mjs")
CATALOG = paths.ENGINE_ROOT / "dist" / "gb-studio-events.json"


def toolchain_gb_studio() -> Path:
    return paths.setup_root() / "toolchain" / ".local" / "vendor" / "gb-studio"


def generate(gb_studio: Path, node: str | None = None) -> str:
    """The catalog text for the GB Studio source at gb_studio, exactly as written to the engine."""
    if not (gb_studio / "src" / "lib" / "events").is_dir():
        raise FileNotFoundError(f"no GB Studio event definitions under {gb_studio}")
    node = node or paths.find_node()["path"]
    if not node:
        raise FileNotFoundError("Node was not found (set HERMRETRO_NODE)")
    done = subprocess.run([node, str(GENERATOR), str(gb_studio)], capture_output=True, text=True, timeout=120)
    if done.returncode != 0:
        raise RuntimeError(done.stderr.strip() or f"event_catalog.mjs exited with {done.returncode}")
    json.loads(done.stdout)
    return done.stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("action", choices=("write", "verify"))
    parser.add_argument("--gb-studio", type=Path, default=None)
    args = parser.parse_args()
    text = generate(args.gb_studio or toolchain_gb_studio())
    if args.action == "write":
        CATALOG.write_text(text)
        print(f"wrote {len(json.loads(text)['events'])} events to {CATALOG}")
        return 0
    if CATALOG.is_file() and CATALOG.read_text() == text:
        print("the event catalog matches GB Studio's event definitions")
        return 0
    print(
        "the event catalog differs from GB Studio's event definitions\n"
        "FIX: python tools/engine/event_catalog.py write, add the engine/CHANGES.md line, "
        "python tools/engine/manifest.py write",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
