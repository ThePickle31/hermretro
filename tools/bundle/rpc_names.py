"""Write page/app/rpc-names.js, the page's list of backend RPC names, from the backend's declarations.

    python tools/bundle/rpc_names.py           write it (only when it changes)
    python tools/bundle/rpc_names.py --check   exit 1 when it is not current; writes nothing

A backend feature declares a page RPC with @rpc("name") in backend/<feature>/rpcs.py (backend/hermes/declare.py).
This reads those files as text (ast) and never imports the backend, so it needs nothing but Python 3.11.
node tools/bundle/bundle.mjs runs it before every build, and its --check (python tools/check.py bundle) fails
when the file is stale. tests/repo/test_lockstep.py also checks it against what the plugin registers.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "page" / "app" / "rpc-names.js"
FIX = "python tools/bundle/rpc_names.py (node tools/bundle/bundle.mjs runs it too), then commit page/app/rpc-names.js"


def declared(root: Path = ROOT) -> list[tuple[str, str]]:
    """Every ``@rpc("name")`` in backend/*/rpcs.py as (name, file), sorted by name."""
    found = []
    for source in sorted((root / "backend").glob("*/rpcs.py")):
        tree = ast.parse(source.read_text(encoding="utf-8"), str(source))
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for call in node.decorator_list:
                if not isinstance(call, ast.Call):
                    continue
                func = call.func
                name = func.id if isinstance(func, ast.Name) else func.attr if isinstance(func, ast.Attribute) else ""
                if name != "rpc":
                    continue
                literal = call.args[0] if len(call.args) == 1 else None
                if not isinstance(literal, ast.Constant) or not isinstance(literal.value, str):
                    raise SystemExit(
                        f"{source.relative_to(root)}:{call.lineno}: @rpc takes one literal name\nFIX: write @rpc(\"name\")"
                    )
                found.append((literal.value, str(source.relative_to(root))))
    names = [name for name, _file in found]
    twice = sorted({name for name in names if names.count(name) > 1})
    if twice:
        raise SystemExit(f"RPC names declared twice: {', '.join(twice)}\nFIX: give each @rpc its own name")
    return sorted(found)


def render(rpcs: list[tuple[str, str]]) -> str:
    lines = [
        "// Generated by tools/bundle/rpc_names.py from the @rpc(\"...\") declarations in backend/<feature>/rpcs.py.",
        "// Do not edit: node tools/bundle/bundle.mjs (or python tools/bundle/rpc_names.py) regenerates it.",
        "import { ID } from './ids.js'",
        "",
        "/** Every page RPC the backend declares: its name -> the method the page calls (`plugin.hermretro.<name>`). */",
        "export const RPC_NAMES = Object.freeze({",
        *(f"  {name}: `plugin.${{ID}}.{name}`," for name, _file in rpcs),
        "})",
        "",
        *(f"export const RPC_{name.upper()} = RPC_NAMES.{name} // {file}" for name, file in rpcs),
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").strip().splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the file is not current")
    args = parser.parse_args(argv)
    text = render(declared())
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
    if args.check:
        if current != text:
            print(f"page/app/rpc-names.js does not match the @rpc declarations in backend/\nFIX: {FIX}")
            return 1
        return 0
    if current != text:
        OUTPUT.write_bytes(text.encode("utf-8"))
        print(f"page/app/rpc-names.js: {text.count('RPC_NAMES.')} RPCs, written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
